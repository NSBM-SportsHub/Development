-- Public information is opt-in: new promotions are drafts until an Admin publishes them.
CREATE TABLE IF NOT EXISTS event_promotions (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    title VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    category ENUM('tournament','trial','camp','sports_day','other') NOT NULL,
    tournament_id BIGINT UNSIGNED NULL,
    venue VARCHAR(160) NOT NULL,
    starts_at DATETIME NOT NULL,
    ends_at DATETIME NOT NULL,
    published TINYINT(1) NOT NULL DEFAULT 0,
    featured TINYINT(1) NOT NULL DEFAULT 1,
    display_order SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    cloud_name VARCHAR(100) NULL,
    public_id VARCHAR(255) NULL,
    version VARCHAR(30) NULL,
    banner_url VARCHAR(1000) NULL,
    created_by BIGINT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at DATETIME NULL,
    PRIMARY KEY (id),
    KEY idx_promotions_public (published, deleted_at, ends_at),
    CONSTRAINT fk_promotions_tournament FOREIGN KEY (tournament_id) REFERENCES tournaments (id),
    CONSTRAINT fk_promotions_creator FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT chk_promotions_dates CHECK (ends_at > starts_at),
    CONSTRAINT chk_promotions_category CHECK ((category = 'tournament' AND tournament_id IS NOT NULL) OR (category <> 'tournament' AND tournament_id IS NULL)),
    CONSTRAINT chk_promotions_banner CHECK ((cloud_name IS NULL AND public_id IS NULL AND version IS NULL AND banner_url IS NULL) OR (cloud_name IS NOT NULL AND public_id IS NOT NULL AND version IS NOT NULL AND banner_url IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
